// Real services, no route mocks. Creates and confirms a synthetic intent after HTTP e2e.
import { chromium, expect } from '../web-app/node_modules/@playwright/test/index.mjs';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const out=path.join(root,'artifacts/browser');
fs.mkdirSync(out,{recursive:true});
const browser=await chromium.launch({headless:true});
const errors=[];
try {
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:15173');
  await page.locator('[data-test=username]').fill('admin');
  await page.locator('[data-test=password]').fill('admin123');
  await page.locator('[data-test=submit]').click();
  const query=page.locator('form').filter({has:page.locator('[data-test=cover-days]')});
  await query.locator('[data-test=skus]').fill('AUD-001,DEM-001');
  await query.locator('[data-test=query]').click();
  await expect(page.locator('[data-test=draft-add-DEM-001]')).toBeVisible();
  await page.locator('[data-test=basis-DEM-001] summary').click();
  await expect(page.locator('[data-test=basis-DEM-001]')).toContainText('整箱建议 48');
  await expect(page.locator('[data-test=basis-DEM-001]')).toContainText('2026-09-03');
  await page.locator('[data-test=draft-add-AUD-001]').click();
  await page.locator('[data-test=draft-review]').click();
  await page.locator('[data-test=draft-submit]').click();
  await expect(page.locator('[data-test=draft-existing]').first()).toContainText('96');
  await page.locator('[data-test=draft-new-intent]').click();
  await page.locator('[data-test=draft-add-DEM-001]').click();
  await page.locator('[data-test=draft-review]').click();
  const createdResponse=page.waitForResponse(r=>r.url().endsWith('/api/agent/tools/create-purchase-order') && r.status()===200);
  await page.locator('[data-test=draft-submit]').click();
  const created=await (await createdResponse).json();
  const po=created.data.items[0].poNo;
  await expect(page.locator('[data-test=draft-result]')).toContainText(po);
  await page.locator('[data-test="po-review-'+po+'"]').click();
  await expect(page.locator('[data-test=po-confirm-summary]')).toContainText('48');
  await page.locator('[data-test=po-confirm-submit]').click();
  await expect(page.locator('[data-test=purchase-status]')).toContainText('库存未变更');
  await page.locator('[data-test=chat-input]').fill('DEM-001 补货');
  await page.locator('[data-test=chat-send]').click();
  await expect(page.locator('.messages')).toContainText('48');
  await page.evaluate(()=>{document.querySelectorAll('.table-wrap').forEach(e=>e.scrollLeft=0);window.scrollTo(0,0);});
  await page.screenshot({path:path.join(out,'desktop.png'),fullPage:true});
  await page.screenshot({path:path.join(out,'dashboard.png')});
  await page.locator('[data-test=form-query]').click();
  await expect(page.locator('[data-test=form-result]')).toContainText('AUD-001');
  const summary=JSON.parse(fs.readFileSync(path.join(root,'artifacts/e2e/summary.json'),'utf8'));
  await page.locator('[data-test=form-kind]').selectOption('run');
  await page.locator('[data-test=form-id]').fill(summary.runId);
  await page.locator('[data-test=form-query]').click();
  await expect(page.locator('[data-test=form-result]')).toContainText(summary.runId);
  await page.locator('[data-test=form-result]').screenshot({path:path.join(out,'form-run.png')});
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:path.join(out,'mobile.png'),fullPage:true});
  const viewer=await browser.newPage({viewport:{width:1440,height:1000}});
  await viewer.goto('http://127.0.0.1:15173');
  await viewer.locator('[data-test=username]').fill('viewer');
  await viewer.locator('[data-test=password]').fill('viewer123');
  await viewer.locator('[data-test=submit]').click();
  await expect(viewer.locator('[data-test=form-query]')).toBeVisible();
  await expect(viewer.locator('[data-test=purchase-draft]')).toHaveCount(0);
  await viewer.locator('[data-test=form-query]').click();
  await expect(viewer.locator('[data-test=form-result]')).toContainText('AUD-001');
  await viewer.screenshot({path:path.join(out,'viewer.png'),fullPage:true});
  if(errors.length) throw new Error(errors.join('\n'));
  fs.writeFileSync(path.join(out,'summary.json'),JSON.stringify({realServices:true,routeMocks:false,pageErrors:errors,checks:['login','AUD/DEM basis','existing-pending rejection','manual create and confirm','viewer read-only','form record','actual Pi run','desktop/mobile']},null,2));
  console.log('Real-service browser checks passed; screenshots:',out);
} finally { await browser.close(); }
