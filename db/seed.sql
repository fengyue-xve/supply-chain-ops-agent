-- ---------- 3. inventory_snapshot（61 天 x 10 SKU = 610 行） ----------
-- 确定性公式生成：stock = 40 + MOD(sku_id*31 + 距窗口起点天数*17, 220)
-- 值刻意不承载业务含义，仅保证稳定可重跑；个别 SKU 近期走势用下方 upsert 覆盖出叙事。
INSERT IGNORE INTO inventory_snapshot (sku_code, snap_date, stock_qty, created_at, updated_at)
SELECT p.sku_code,
       DATE_ADD(DATE '2026-07-05', INTERVAL ds.n DAY),
       40 + MOD(p.id * 31 + ds.n * 17, 220),
       '2026-09-03 09:10:00.000',
       '2026-09-03 09:10:00.000'
FROM product p
CROSS JOIN (
    WITH RECURSIVE day_seq AS (
        SELECT 0 AS n
        UNION ALL
        SELECT n + 1 FROM day_seq WHERE n < 60
    )
    SELECT n FROM day_seq
) AS ds;

